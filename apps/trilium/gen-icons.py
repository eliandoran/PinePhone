#!/usr/bin/env python3
"""Boxicons for Trilium's note icons, as C: gen-icons.py boxicons icons.c

boxicons/ holds Boxicons 2.1.4's TrueType font (the npm package's fonts/boxicons.ttf,
the version Trilium's client depends on; MIT, its LICENSE) and Trilium's manifest for
it (TriliumNext's packages/trilium-core/src/services/icon_pack_boxicons-v2.json): each
icon's name ("bx-folder") and the character it is in the font. Out come the font's
bytes for lv_tiny_ttf_create_data() and the names sorted, with their characters, for
bsearch() (trilium.h's struct tr_boxicon).
"""

import json
import sys


def main():
    folder, out = sys.argv[1], sys.argv[2]
    with open(f"{folder}/boxicons.ttf", "rb") as f:
        ttf = f.read()
    with open(f"{folder}/manifest.json", encoding="utf-8") as f:
        icons = json.load(f)["icons"]
    # One character each (bx-empty has none: Trilium draws nothing for it either)
    names = sorted((name, ord(icon["glyph"])) for name, icon in icons.items() if len(icon["glyph"]) == 1)

    lines = ["/* Generated by gen-icons.py from boxicons/: Boxicons 2.1.4 (MIT) */", "",
             "#include <stddef.h>", "#include <stdint.h>", "", '#include "trilium.h"', "",
             "const uint8_t tr_boxicons_ttf[] = {"]
    for i in range(0, len(ttf), 16):
        lines.append("\t" + ",".join(f"0x{b:02x}" for b in ttf[i:i + 16]) + ",")
    lines += ["};", "const size_t tr_boxicons_ttf_size = sizeof(tr_boxicons_ttf);", "",
              "const struct tr_boxicon tr_boxicons[] = {"]
    lines += [f'\t{{"{name}", 0x{cp:x}}},' for name, cp in names]
    lines += ["};", "const size_t tr_boxicons_count = sizeof(tr_boxicons) / sizeof(tr_boxicons[0]);", ""]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
