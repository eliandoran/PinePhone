#!/usr/bin/env bash
#
# Generates shortcodes.c: the emoji's names as GitHub writes them in Markdown
# (:white_check_mark:), from emoji-datasource's short names (emoji.json, the
# archive phone-ui's emoji come from), sorted for bsearch(). Each emoji is UTF-8
# as GitHub shows it (fully qualified).
#
# Run in `nix develop` (jq), after Buildroot downloaded noto-emoji:
#   apps/github/gen-shortcodes.sh
#

set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
pkg="$here/../../external/package"
version="$(sed -n 's/^NOTO_EMOJI_VERSION = //p' "$pkg/noto-emoji/noto-emoji.mk")"
archive="$here/../../dl/noto-emoji/emoji-datasource-google-$version.tgz"

{
	echo "/* Generated by gen-shortcodes.sh from emoji-datasource-google $version (emoji.json), do not edit */"
	echo
	echo '#include "github.h"'
	echo
	echo "const struct shortcode shortcodes[] = {"
	tar -xzOf "$archive" package/emoji.json | jq -r '
		.[] | (.unified | split("-") | map("0x" + . | ltrimstr("0x") | explode
			| reduce .[] as $d (0; . * 16 + (if $d >= 65 then $d - 55 else $d - 48 end))) | implode) as $e
		| .short_names[] | "\t{\"\(.)\", \"\($e)\"},"' | LC_ALL=C sort -t '"' -k2,2 -u
	echo "};"
	echo
	echo "const unsigned shortcode_count = sizeof(shortcodes) / sizeof(shortcodes[0]);"
} > "$here/shortcodes.c.tmp"
mv "$here/shortcodes.c.tmp" "$here/shortcodes.c"
echo "$here/shortcodes.c: $(grep -c '^	{' "$here/shortcodes.c") names"
